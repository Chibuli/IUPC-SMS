"""PG15 checks in an OWNED disposable network-disabled container; never an app DB.

Uses only a cached image (--pull never), no volumes, ports, connection URLs or
Supabase CLI operations. Minimal Auth stubs simulate authenticated identities;
this does not claim a full Supabase Auth/PostgREST end-to-end deployment test.
"""
from pathlib import Path
import importlib.util
import json
import subprocess
import sys
import time
import uuid

ROOT = Path(__file__).resolve().parents[1]
IMAGE = 'public.ecr.aws/supabase/postgres:15.19.0.007'
NAME = 'iupc-phase2b-disposable-' + uuid.uuid4().hex[:12]
OUT = ROOT / '.local-migration/phase2b-review'
spec = importlib.util.spec_from_file_location('phase2a', ROOT / 'scripts/verify-enrollment-history.py')
phase2a = importlib.util.module_from_spec(spec)
sys.dont_write_bytecode = True
spec.loader.exec_module(phase2a)

def docker(*args, input=None, check=True):
    result = subprocess.run(['docker', *args], input=input, text=True, encoding='utf-8', capture_output=True, timeout=60)
    if check and result.returncode:
        raise RuntimeError(result.stderr + result.stdout)
    return result

def sql(text, check=True):
    return docker('exec', '-i', NAME, 'psql', '-X', '-h', '/tmp', '-U', 'postgres', '-d', 'postgres',
                  '-v', 'ON_ERROR_STOP=1', '-v', 'VERBOSITY=verbose', '-At', input=text, check=check)

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    started = False
    logs = []
    try:
        docker('run', '-d', '--pull', 'never', '--network', 'none', '--user', 'postgres',
               '--tmpfs', '/tmp:rw,mode=1777', '--label', 'iupc.phase=2b-disposable',
               '--name', NAME, '--entrypoint', 'sh', IMAGE, '-c',
               'initdb -D /tmp/iupc-test -U postgres -A trust --no-locale --encoding=UTF8 > /tmp/init.log && exec postgres -D /tmp/iupc-test -k /tmp -h ""')
        started = True
        for _ in range(100):
            if docker('exec', NAME, 'pg_isready', '-h', '/tmp', '-U', 'postgres', check=False).returncode == 0:
                break
            time.sleep(.1)
        else:
            raise RuntimeError(docker('logs', NAME).stdout)
        version = sql('show server_version;').stdout.strip()
        assert version.startswith('15.'), version
        logs.append('PostgreSQL ' + version)
        sql(phase2a.BOOTSTRAP)
        migrations = sorted((ROOT / 'supabase/migrations').glob('*.sql'))
        for migration in migrations:
            if migration.name >= phase2a.MIGRATION.name:
                continue
            sql('begin;\n' + migration.read_text(encoding='utf-8') + '\ncommit;')
            logs.append('APPLIED ' + migration.name)
        sql((ROOT / 'supabase/tests/fixtures/enrollment-history-baseline.sql').read_text(encoding='utf-8'))
        snapshot = "select jsonb_build_object('students',(select jsonb_agg(to_jsonb(x) order by id) from public.students x),'marks',(select jsonb_agg(to_jsonb(x) order by id) from public.marks x),'subjects',(select jsonb_agg(to_jsonb(x) order by student_id,subject_id) from public.student_subjects x),'classes',(select jsonb_agg(to_jsonb(x) order by id) from public.classes x),'exams',(select jsonb_agg(to_jsonb(x) order by id) from public.exams x),'reports',(select jsonb_agg(to_jsonb(x) order by id) from public.report_cards x))::text;"
        before = sql(snapshot).stdout
        for migration in migrations:
            if migration.name < phase2a.MIGRATION.name:
                continue
            sql('begin;\n' + migration.read_text(encoding='utf-8') + '\ncommit;')
            logs.append('APPLIED ADDITIVE UPGRADE ' + migration.name)
        assert before == sql(snapshot).stdout, 'Additive upgrade changed legacy fictional data'
        assert sql('select (select count(*) from public.student_school_enrollment_history)+(select count(*) from public.student_class_enrollment_history)+(select count(*) from public.student_subject_enrollment_history);').stdout.strip() == '0'
        logs.append('UPGRADE: legacy fixtures unchanged; no historical backfill')
        for test in ['enrollment_history.test.sql', 'enrollment_history_admin.test.sql']:
            output = sql((ROOT / 'supabase/tests' / test).read_text(encoding='utf-8')).stdout
            logs.append(test + '\n' + output)
            assert before == sql(snapshot).stdout, 'Legacy fictional records changed'
        # Replay the actual guided-transition payloads captured from the browser
        # against real Phase 2A guards, replacing only seed IDs generated by DB.
        plans_file = OUT / 'ui-plans.json'
        if plans_file.is_file():
            for case in json.loads(plans_file.read_text(encoding='utf-8')):
                identity = "select set_config('request.jwt.claim.sub','61000000-0000-4000-8000-000000000001',true);set local role authenticated;"
                setup = '''
                  select public.append_enrollment_history('school',pg_temp.seed('{"school_state":"enrolled","entry_kind":"admission"}')) as seed_school \\gset
                  select public.append_enrollment_history('class',pg_temp.seed(jsonb_build_object('school_history_id',:'seed_school','class_id','64000000-0000-4000-8000-000000000001','subject_scope_complete',true))) as seed_class \\gset
                  select public.append_enrollment_history('subject',pg_temp.seed(jsonb_build_object('class_history_id',:'seed_class','subject_id','65000000-0000-4000-8000-000000000001','subject_state','enrolled'))) as seed_subject \\gset
                '''
                if not case['seed']['class']:
                    setup = setup.split("select public.append_enrollment_history('class'")[0]
                    setup = setup.replace('"school_state":"enrolled","entry_kind":"admission"', '"school_state":"not_enrolled","entry_kind":"unknown"')
                    setup += "select '00000000-0000-0000-0000-000000000000' as seed_class, '00000000-0000-0000-0000-000000000000' as seed_subject \\gset\n"
                payload = json.dumps(case['steps']).replace("'", "''")
                test_sql = '''begin;
                  create function pg_temp.seed(patch jsonb) returns jsonb language sql as $$
                    select '{"school_id":"62000000-0000-4000-8000-000000000001","student_id":"67000000-0000-4000-8000-000000000002","term_id":"66000000-0000-4000-8000-000000000001","coverage_kind":"whole_term","start_precision":"term_start","end_precision":"term_end","evidence_state":"confirmed","source_type":"class_register","source_reference":"FICTIONAL-BROWSER-SEED","reason":"Fictional browser seed"}'::jsonb||patch
                  $$;
                  do $$begin execute format('grant usage on schema %I to authenticated',pg_my_temp_schema()::regnamespace::text);end$$;
                  grant execute on function pg_temp.seed(jsonb) to authenticated;
                ''' + identity + setup + "select replace(replace(replace('" + payload + "','80000000-0000-4000-8000-000000000001',:'seed_school'),'80000000-0000-4000-8000-000000000002',:'seed_class'),'80000000-0000-4000-8000-000000000003',:'seed_subject') as actual_steps \\gset\n" + '''
                  select public.apply_enrollment_history_change('62000000-0000-4000-8000-000000000001','67000000-0000-4000-8000-000000000002',gen_random_uuid(),public.read_enrollment_history('62000000-0000-4000-8000-000000000001','67000000-0000-4000-8000-000000000002')->>'version',:'actual_steps'::jsonb);
                  select count(*) from public.enrollment_history_operations;
                  rollback;
                '''
                result = sql(test_sql).stdout
                assert '"applied": true' in result, result
                logs.append('BROWSER PLAN SQL PASSED: ' + case['name'])
                assert before == sql(snapshot).stdout
        else:
            logs.append('BROWSER PLAN SQL: not run; first run scripts/verify-enrollment-history-ui.mjs')
        # Actual competing sessions: second stale snapshot must fail after waiting.
        school='62000000-0000-4000-8000-000000000001'
        student='67000000-0000-4000-8000-000000000002'
        identity="select set_config('request.jwt.claim.sub','61000000-0000-4000-8000-000000000001',true);set local role authenticated;"
        version = sql(f"begin;{identity}select public.read_enrollment_history('{school}','{student}')->>'version';rollback;").stdout.splitlines()[-2]
        step = json.dumps([{'key':'school','axis':'school','input':{'term_id':'66000000-0000-4000-8000-000000000003','reason':'Fictional concurrency','coverage_kind':'unknown'}}])
        def command(request):
            return f"select public.apply_enrollment_history_change('{school}','{student}','{request}','{version}','{step}'::jsonb);"
        holder_script = "set application_name='iupc_phase2b_holder';begin;" + identity + command(str(uuid.uuid4())) + 'select pg_sleep(2);commit;'
        holder = subprocess.Popen(['docker','exec','-i',NAME,'psql','-X','-h','/tmp','-U','postgres','-v','ON_ERROR_STOP=1','-At'], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        holder.stdin.write(holder_script);holder.stdin.close()
        try:
            for _ in range(40):
                if sql("select exists(select 1 from pg_stat_activity where application_name='iupc_phase2b_holder' and wait_event='PgSleep');").stdout.strip() == 't': break
                time.sleep(.05)
            else: raise AssertionError('Concurrency holder did not reach controlled wait')
            contender = sql('begin;' + identity + command(str(uuid.uuid4())) + 'commit;', check=False)
            assert contender.returncode != 0 and 'PT409' in contender.stderr, contender.stderr
            assert holder.wait(timeout=10) == 0, holder.stderr.read()
            logs.append('REAL TWO-SESSION STALE SNAPSHOT: denied PT409 after serialization')
        finally:
            if holder.poll() is None: holder.terminate();holder.wait(timeout=10)
        assert before == sql(snapshot).stdout
        logs.append('LEGACY FICTIONAL STUDENTS/MARKS/ENROLLMENTS/CLASSES/EXAMS/REPORTS UNCHANGED')
        print('\n'.join(line for line in '\n'.join(logs).splitlines() if 'ASSERTIONS=' in line or line.startswith(('PostgreSQL','REAL','LEGACY','UPGRADE','BROWSER'))))
    finally:
        (OUT / 'database-results.txt').write_text('\n'.join(logs), encoding='utf-8')
        if started:
            # Only the exact container created above; no existing containers/volumes.
            docker('stop', '-t', '5', NAME, check=False)
            docker('rm', NAME, check=False)

if __name__ == '__main__':
    main()
